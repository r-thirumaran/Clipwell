import AppKit

/// Watches `NSPasteboard.general` and turns every new copy into a `ClipItem`.
///
/// `NSPasteboard` publishes no change notification of any kind, so polling `changeCount` is
/// the only mechanism available. 0.3 s comfortably meets the "in history within 0.5 s" bar
/// while costing a single integer read per tick — `changeCount` does not touch the pasteboard
/// contents, so the poll is genuinely free until something actually changes.
final class ClipboardMonitor {

    /// Marker types published by well-behaved apps that do not want their data recorded.
    /// Password managers set `ConcealedType`; `TransientType` and `AutoGeneratedType` cover
    /// scratch data and machine-generated content. See nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private let store: ClipboardStore
    private var timer: DispatchSourceTimer?
    private var lastChangeCount: Int

    /// Set by `Paster` to the `changeCount` produced by our own write, so pasting an item does
    /// not re-capture it with SnapBoard listed as the source app.
    var suppressedChangeCount: Int?

    init(store: ClipboardStore) {
        self.store = store
        // Seed from the current value so whatever is already on the pasteboard at launch is
        // not re-recorded on every start.
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Lifecycle

    func start(interval: TimeInterval = 0.3) {
        stop()
        let timer = DispatchSource.makeTimerSource(queue: .main)
        timer.schedule(deadline: .now() + interval,
                       repeating: interval,
                       leeway: .milliseconds(50))
        timer.setEventHandler { [weak self] in self?.poll() }
        timer.resume()
        self.timer = timer
    }

    func stop() {
        timer?.cancel()
        timer = nil
    }

    // MARK: - Polling

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if let suppressed = suppressedChangeCount, suppressed == changeCount {
            suppressedChangeCount = nil
            return
        }
        guard !isConcealed else { return }
        guard let item = capture() else { return }
        store.insert(item)
    }

    /// Honours the opt-out markers. Checked per pasteboard item as well as at the pasteboard
    /// level, because a multi-item pasteboard only reports the first item's types up top.
    private var isConcealed: Bool {
        if pasteboard.types?.contains(where: { ClipboardMonitor.ignoredTypes.contains($0) }) == true {
            return true
        }
        guard let items = pasteboard.pasteboardItems else { return false }
        return items.contains { item in
            item.types.contains { ClipboardMonitor.ignoredTypes.contains($0) }
        }
    }

    // MARK: - Capture

    /// The frontmost app at the moment the change was noticed. Polling means this is an
    /// inference rather than a fact — a copy triggered by a background app would be
    /// misattributed — but for the user-driven ⌘C that produces essentially all history, it
    /// is correct.
    private var sourceBundleID: String? {
        NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }

    private func capture() -> ClipItem? {
        let string = pasteboard.string(forType: .string)

        // File URLs first: dragging or copying files in Finder also puts a text
        // representation on the pasteboard, and the files are the more useful reading.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let joined = urls.map(\.path).joined(separator: "\n")
            return ClipItem(kind: .fileURLs,
                            plainText: joined,
                            fileURLs: urls,
                            sourceAppBundleID: sourceBundleID,
                            fingerprint: ClipItem.fingerprint(for: "files:" + joined))
        }

        // Images next. A copied image may also carry a caption or source URL as text; that is
        // kept in `plainText` so search still finds it.
        if let png = pngData() {
            let id = UUID()
            Storage.write(png, to: Storage.imageURL(for: id))
            let size = NSImage(data: png)?.size
            return ClipItem(id: id,
                            kind: .image,
                            plainText: string,
                            hasImage: true,
                            imageWidth: size.map { Int($0.width) },
                            imageHeight: size.map { Int($0.height) },
                            sourceAppBundleID: sourceBundleID,
                            fingerprint: ClipItem.fingerprint(for: png))
        }

        // Rich text: keep the RTF for a faithful paste and the plain string for everything else.
        if let rtf = pasteboard.data(forType: .rtf), let string, !string.isEmpty {
            return ClipItem(kind: .rtf,
                            plainText: string,
                            rtfData: rtf,
                            sourceAppBundleID: sourceBundleID,
                            fingerprint: ClipItem.fingerprint(for: "rtf:" + string))
        }

        if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipItem(kind: .text,
                            plainText: string,
                            sourceAppBundleID: sourceBundleID,
                            fingerprint: ClipItem.fingerprint(for: string))
        }

        return nil
    }

    /// PNG bytes for whatever image is on the pasteboard, transcoding from TIFF when an app
    /// only offers that (Preview and most native apps do).
    private func pngData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
